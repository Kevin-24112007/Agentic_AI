drop function if exists public.create_thread(uuid, text);
drop function if exists public.create_thread;

create or replace function public.create_thread(p_id uuid, p_student_id text)
returns uuid language plpgsql as $$
begin
    insert into public.agent_thread (id, student_id) values (p_id, p_student_id);
    return p_id;
end $$;


drop function if exists public.append_message;

create or replace function public.append_message(
    p_thread_id uuid, p_role text, p_text text)
returns integer language plpgsql as $$
declare n integer;
begin
    -- Lock the thread so two appends cannot pick the same seq.
    perform 1 from public.agent_thread where id = p_thread_id for update;
    select coalesce(max(m.seq), 0) + 1 into n
    from public.agent_message m where m.thread_id = p_thread_id;
    insert into public.agent_message (thread_id, seq, role, text)
    values (p_thread_id, n, p_role, p_text);
    return n;
end $$;


drop function if exists public.enqueue_run;

create or replace function public.enqueue_run(
    p_run_id uuid, p_thread_id uuid, p_text text,
    p_model text, p_max_attempts integer)
returns uuid language plpgsql as $$
begin
    -- The user's message and its queued run are saved together or not at all.
    perform public.append_message(p_thread_id, 'user', p_text);
    insert into public.agent_run
        (id, thread_id, status, model, max_attempts, available_at)
    values (p_run_id, p_thread_id, 'queued', p_model, p_max_attempts, now());
    return p_run_id;
end $$;


drop function if exists public.claim_next_run;

create or replace function public.claim_next_run(
    p_worker_id text, p_lease_seconds double precision)
returns table (run_id uuid, thread_id uuid, attempts integer)
language plpgsql as $$
declare r public.agent_run%rowtype;
begin
    -- SKIP LOCKED is what lets several workers poll the same queue without
    -- two of them claiming the same run.
    select * into r from public.agent_run
    where status = 'queued' and available_at <= now()
    order by available_at, created_at
    for update skip locked
    limit 1;

    if not found then
        return;
    end if;

    -- `attempts` is also an OUT column of this function, so the right-hand
    -- side must be qualified through an alias. Unqualified, PostgreSQL raises
    -- "column reference attempts is ambiguous" and no run is ever claimed.
    update public.agent_run ar
    set status      = 'running',
        lease_owner = p_worker_id,
        lease_until = now() + make_interval(secs => p_lease_seconds),
        attempts    = ar.attempts + 1,
        started_at  = coalesce(ar.started_at, now())
    where ar.id = r.id;

    return query select r.id, r.thread_id, r.attempts + 1;
end $$;


-- Returns a plain boolean, never an empty set: the Python side can read the
-- answer without guarding against a zero-row response.
drop function if exists public.heartbeat_run;

create or replace function public.heartbeat_run(
    p_run_id uuid, p_worker_id text, p_lease_seconds double precision)
returns boolean language plpgsql as $$
declare n integer;
begin
    update public.agent_run
    set lease_until = now() + make_interval(secs => p_lease_seconds)
    where id = p_run_id and status = 'running' and lease_owner = p_worker_id;
    get diagnostics n = row_count;
    return n = 1;
end $$;


drop function if exists public.reap_expired;

create or replace function public.reap_expired()
returns table (id uuid) language plpgsql as $$
declare r public.agent_run%rowtype;
begin
    for r in
        select * from public.agent_run
        where status = 'running' and lease_until < now()
        for update skip locked
    loop
        if r.attempts >= r.max_attempts then
            update public.agent_run
            set status = 'dead', error_code = 'lease_expired',
                lease_owner = null, lease_until = null, finished_at = now()
            where public.agent_run.id = r.id;
        else
            update public.agent_run
            set status = 'queued', error_code = 'lease_expired',
                lease_owner = null, lease_until = null, available_at = now()
            where public.agent_run.id = r.id;
        end if;
        id := r.id;
        return next;
    end loop;
end $$;


drop function if exists public.record_model_step;

create or replace function public.record_model_step(
    p_run_id uuid, p_seq integer, p_tokens_in integer,
    p_tokens_out integer, p_text text, p_tool_calls jsonb)
returns bigint language plpgsql as $$
declare sid bigint;
begin
    insert into public.agent_run_step
        (run_id, seq, kind, tokens_in, tokens_out, text, tool_calls)
    values (p_run_id, p_seq, 'model', p_tokens_in, p_tokens_out, p_text, p_tool_calls)
    returning agent_run_step.id into sid;

    update public.agent_run
    set tokens_in  = tokens_in  + p_tokens_in,
        tokens_out = tokens_out + p_tokens_out
    where agent_run.id = p_run_id;

    return sid;
end $$;


drop function if exists public.record_tool_call;

create or replace function public.record_tool_call(
    p_run_id uuid, p_seq integer, p_name text, p_args jsonb,
    p_result jsonb, p_ok boolean, p_latency_ms integer, p_idempotency_key text)
returns bigint language plpgsql as $$
declare sid bigint; tid bigint;
begin
    insert into public.agent_run_step (run_id, seq, kind)
    values (p_run_id, p_seq, 'tool')
    returning agent_run_step.id into sid;

    insert into public.agent_tool_call
        (run_step_id, tool_name, args, result, ok, latency_ms, idempotency_key)
    values (sid, p_name, p_args, p_result, p_ok, p_latency_ms, p_idempotency_key)
    returning agent_tool_call.id into tid;

    return tid;
end $$;


drop function if exists public.load_run_steps;

create or replace function public.load_run_steps(p_run_id uuid)
returns table (
    seq integer, kind text, step_text text, tool_calls jsonb,
    tool_name text, args jsonb, result jsonb, ok boolean)
language sql as $$
    select s.seq, s.kind, s.text, s.tool_calls,
           t.tool_name, t.args, t.result, t.ok
    from public.agent_run_step s
    left join public.agent_tool_call t on t.run_step_id = s.id
    where s.run_id = p_run_id
    order by s.seq;
$$;


drop function if exists public.complete_run;

create or replace function public.complete_run(
    p_run_id uuid, p_worker_id text, p_reply text)
returns boolean language plpgsql as $$
declare tid uuid;
begin
    -- Only the worker that still owns the run may finish it.
    select thread_id into tid from public.agent_run
    where id = p_run_id and status = 'running' and lease_owner = p_worker_id
    for update;

    if tid is null then
        return false;
    end if;

    perform public.append_message(tid, 'model', p_reply);
    update public.agent_run
    set status = 'succeeded', lease_owner = null, lease_until = null,
        error_code = null, finished_at = now()
    where id = p_run_id;

    return true;
end $$;


drop function if exists public.request_cancel;

create or replace function public.request_cancel(p_run_id uuid)
returns text language plpgsql as $$
declare s text;
begin
    select agent_run.status into s from public.agent_run
    where id = p_run_id for update;

    if s is null then
        return null;                       -- no such run
    elsif s = 'queued' then
        update public.agent_run
        set status = 'cancelled', finished_at = now() where id = p_run_id;
        return 'cancelled';
    elsif s = 'running' then
        -- Flag it. Its worker stops between steps, never mid tool call.
        update public.agent_run set cancel_requested = true where id = p_run_id;
    end if;
    return s;
end $$;


drop function if exists public.mark_cancelled;

create or replace function public.mark_cancelled(p_run_id uuid, p_worker_id text)
returns boolean language plpgsql as $$
declare n integer;
begin
    update public.agent_run
    set status = 'cancelled', lease_owner = null,
        lease_until = null, finished_at = now()
    where id = p_run_id and status = 'running' and lease_owner = p_worker_id;
    get diagnostics n = row_count;
    return n = 1;
end $$;


drop function if exists public.fail_attempt;

create or replace function public.fail_attempt(
    p_run_id uuid, p_worker_id text, p_error_code text,
    p_retryable boolean, p_backoff_seconds double precision default 2.0)
returns text language plpgsql as $$
declare a integer; mx integer; new_status text; delay_seconds double precision;
begin
    select attempts, max_attempts into a, mx from public.agent_run
    where id = p_run_id and status = 'running' and lease_owner = p_worker_id
    for update;

    if a is null then
        return null;                       -- this worker no longer owns it
    end if;

    if p_retryable and a < mx then
        delay_seconds := p_backoff_seconds * power(2, a - 1);
        update public.agent_run
        set status = 'queued', error_code = p_error_code,
            lease_owner = null, lease_until = null,
            available_at = now() + make_interval(secs => delay_seconds)
        where id = p_run_id;
        return 'queued';
    end if;

    new_status := case when p_retryable then 'dead' else 'failed' end;
    update public.agent_run
    set status = new_status, error_code = p_error_code,
        lease_owner = null, lease_until = null, finished_at = now()
    where id = p_run_id;
    return new_status;
end $$;


