-- ============================================================================
-- DOMAIN RPCS
--
-- Every side effect is one PostgreSQL transaction: check the key, do the work,
-- store the result. The tool cannot skip the policy or the balance check,
-- because the check is inside the function that does the write.
-- ============================================================================

drop function if exists public.apply_leave;

create or replace function public.apply_leave(
    p_student_id      bigint,
    p_start_date      date,
    p_end_date        date,
    p_days            integer,
    p_reason          text,
    p_idempotency_key text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    old_result     jsonb;
    s              public.leave_student%rowtype;
    existing       public.leave_request%rowtype;
    max_days       integer;
    new_request_id bigint;
    result         jsonb;
begin
    -- Same run, same step, same arguments: hand back what happened last time.
    select li.result into old_result
    from public.leave_idempotency li where li.key = p_idempotency_key;
    if old_result is not null then
        return old_result || jsonb_build_object('replayed', true);
    end if;

    if p_days <= 0 then
        result := jsonb_build_object('error', 'invalid_days');
    elsif p_start_date > p_end_date then
        result := jsonb_build_object('error', 'invalid_date_range');
    elsif length(trim(coalesce(p_reason, ''))) = 0 then
        result := jsonb_build_object('error', 'invalid_reason');
    else
        select lp.value into max_days
        from public.leave_policy lp where lp.name = 'max_days_per_application';

        if max_days is null then
            result := jsonb_build_object('error', 'policy_missing');
        elsif p_days > max_days then
            result := jsonb_build_object('error', 'policy_limit', 'max_days', max_days);
        else
            -- Lock the student row: two concurrent workers cannot both read
            -- balance 3, both see "enough", and both deduct.
            select * into s from public.leave_student
            where id = p_student_id for update;

            if not found then
                result := jsonb_build_object('error', 'unknown_student');
            else
                -- Look for an identical request BEFORE judging the balance.
                -- Otherwise repeating an application that already spent the
                -- balance reports insufficient_balance instead of
                -- already_applied, and the two backends disagree.
                select * into existing from public.leave_request
                where student_id = p_student_id
                  and start_date = p_start_date
                  and end_date   = p_end_date;

                if found then
                    result := jsonb_build_object(
                        'request_id', existing.id,
                        'status',     'already_applied',
                        'days',       existing.days);
                elsif p_days > s.leave_balance then
                    result := jsonb_build_object(
                        'error',     'insufficient_balance',
                        'balance',   s.leave_balance,
                        'requested', p_days);
                else
                    update public.leave_student
                    set leave_balance = leave_balance - p_days
                    where id = p_student_id;

                    insert into public.leave_request
                        (student_id, start_date, end_date, days, reason, status)
                    values
                        (p_student_id, p_start_date, p_end_date, p_days, p_reason, 'approved')
                    returning id into new_request_id;

                    result := jsonb_build_object(
                        'request_id', new_request_id,
                        'status',     'approved',
                        'days',       p_days);
                end if;
            end if;
        end if;
    end if;

    insert into public.leave_idempotency (key, tool_name, result)
    values (p_idempotency_key, 'apply_leave', result)
    on conflict (key) do nothing;

    return result;
end $$;


drop function if exists public.withdraw_leave;

create or replace function public.withdraw_leave(
    p_student_id      bigint,
    p_request_id      bigint,
    p_idempotency_key text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    old_result jsonb;
    r          public.leave_request%rowtype;
    result     jsonb;
begin
    select li.result into old_result
    from public.leave_idempotency li where li.key = p_idempotency_key;
    if old_result is not null then
        return old_result || jsonb_build_object('replayed', true);
    end if;

    select * into r from public.leave_request
    where id = p_request_id and student_id = p_student_id for update;

    if not found then
        result := jsonb_build_object('error', 'unknown_request');
    elsif r.status = 'withdrawn' then
        -- Safe to repeat on its own: the days are not restored twice.
        result := jsonb_build_object(
            'request_id', r.id, 'status', 'already_withdrawn', 'days_restored', 0);
    else
        update public.leave_student
        set leave_balance = leave_balance + r.days where id = p_student_id;
        update public.leave_request set status = 'withdrawn' where id = r.id;
        result := jsonb_build_object(
            'request_id', r.id, 'status', 'withdrawn', 'days_restored', r.days);
    end if;

    insert into public.leave_idempotency (key, tool_name, result)
    values (p_idempotency_key, 'withdraw_leave', result)
    on conflict (key) do nothing;

    return result;
end $$;


drop function if exists public.notify_hod;

create or replace function public.notify_hod(
    p_roll_no         text,
    p_message         text,
    p_idempotency_key text
) returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
    old_result  jsonb;
    existing_id bigint;
    daily_key   text;
    result      jsonb;
begin
    select li.result into old_result
    from public.leave_idempotency li where li.key = p_idempotency_key;
    if old_result is not null then
        return old_result || jsonb_build_object('replayed', true);
    end if;

    if length(trim(coalesce(p_message, ''))) = 0 or length(p_message) > 160 then
        result := jsonb_build_object('error', 'invalid_message');
    else
        -- Second layer, independent of the run: same student + same collapsed
        -- message + same day is one notification, whatever key arrives.
        -- Note '\s+' with ONE backslash. '\\s+' matches a literal backslash.
        daily_key := encode(sha256(convert_to(
              lower(trim(p_roll_no))
           || '|' || regexp_replace(trim(p_message), '\s+', ' ', 'g')
           || '|' || current_date::text, 'UTF8')), 'hex');

        insert into public.leave_notification (roll_no, message, dedupe_key)
        values (p_roll_no, p_message, daily_key)
        on conflict (dedupe_key) do nothing
        returning id into existing_id;

        if existing_id is null then
            select n.id into existing_id
            from public.leave_notification n where n.dedupe_key = daily_key;
            result := jsonb_build_object(
                'notification_id', existing_id, 'status', 'queued', 'duplicate', true);
        else
            result := jsonb_build_object(
                'notification_id', existing_id, 'status', 'queued', 'duplicate', false);
        end if;
    end if;

    insert into public.leave_idempotency (key, tool_name, result)
    values (p_idempotency_key, 'notify_hod', result)
    on conflict (key) do nothing;

    return result;
end $$;


-- Counting rows over PostgREST needs a column every table has. leave_policy is
-- keyed by name and leave_idempotency by key, so `select id` does not work for
-- them. One function keeps the client simple and the table list closed.
drop function if exists public.table_count;

create or replace function public.table_count(p_table text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare n bigint;
begin
    if p_table not in (
        'leave_student', 'leave_holiday', 'leave_policy', 'leave_request',
        'leave_notification', 'leave_idempotency', 'agent_thread',
        'agent_message', 'agent_run', 'agent_run_step', 'agent_tool_call') then
        raise exception 'unknown table %', p_table;
    end if;
    execute format('select count(*) from public.%I', p_table) into n;
    return n;
end $$;


