-- ACCESS CONTROL
--
-- This repository is public, so the database is locked down on purpose.
-- Row Level Security is enabled on every table and NO policy is created, so
-- the anon and authenticated keys (the ones that could leak into a browser)
-- can read nothing. The service-role key bypasses RLS and is the only way in,
-- and it lives in .env, which is gitignored.
-- ============================================================================

