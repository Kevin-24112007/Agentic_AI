-- ============================================================================
-- Campus Leave Agent - Supabase / PostgreSQL migration
--
-- Run this ONCE in the Supabase SQL Editor (paste the whole file, press Run).
-- It is safe to run again: every statement is idempotent.
--
-- One Supabase project gives you one PostgreSQL database, so the brief's two
-- stores live here as two clearly separated table namespaces:
--
--   leave_*  domain store   students, holidays, policy, requests, notifications
--   agent_*  runtime store  threads, messages, runs, steps, tool calls
--
-- Nothing in leave_* knows about agents, and nothing in agent_* knows about
-- leave. Section 3 of the README explains the trade-off.
--
-- No extensions are required. sha256() and encode() are built into
-- PostgreSQL 11+, so this does not depend on pgcrypto living in the
-- `extensions` schema (which is where Supabase puts it, and which would be
-- invisible to a function pinned to `search_path = public`).
-- ============================================================================


-- ============================================================================
-- DOMAIN STORE
-- ============================================================================

create table if not exists public.leave_student (
    id            bigint generated by default as identity primary key,
    roll_no       text    not null unique,
    name          text    not null,
    dept          text    not null,
    leave_balance integer not null check (leave_balance >= 0)
);

create table if not exists public.leave_holiday (
    id           bigint generated by default as identity primary key,
    holiday_date date not null unique,
    name         text not null
);

-- The business rule lives here, as data. Not in a prompt, not in Python.
create table if not exists public.leave_policy (
    name  text primary key,
    value integer not null check (value >= 0)
);

create table if not exists public.leave_request (
    id         bigint generated by default as identity primary key,
    student_id bigint  not null references public.leave_student(id),
    start_date date    not null,
    end_date   date    not null,
    days       integer not null check (days > 0),
    reason     text    not null,
    status     text    not null check (status in ('approved', 'withdrawn')),
    created_at timestamptz not null default now(),
    -- Makes apply_leave safe to repeat on its own, with no key involved.
    unique (student_id, start_date, end_date)
);
create index if not exists leave_request_by_student
    on public.leave_request (student_id, start_date);

create table if not exists public.leave_notification (
    id         bigint generated by default as identity primary key,
    roll_no    text not null,
    message    text not null,
    -- Same student, same message, same day => one row. The second safe-to-
    -- repeat side effect.
    dedupe_key text not null unique,
    created_at timestamptz not null default now()
);

-- Every write effect stores its key and its result in the same transaction as
-- the effect itself. A crash between the effect and the worker recording it
-- replays the stored result instead of doing the work twice.
create table if not exists public.leave_idempotency (
    key        text primary key,
    tool_name  text  not null,
    result     jsonb not null,
    created_at timestamptz not null default now()
);


-- ============================================================================
-- AGENT RUNTIME STORE
-- ============================================================================

create table if not exists public.agent_thread (
    id         uuid primary key,
    student_id text not null,
    created_at timestamptz not null default now()
);

create table if not exists public.agent_message (
    id         bigint generated by default as identity primary key,
    thread_id  uuid    not null references public.agent_thread(id),
    seq        integer not null,
    role       text    not null check (role in ('user', 'model')),
    text       text    not null,
    created_at timestamptz not null default now(),
    unique (thread_id, seq)
);

create table if not exists public.agent_run (
    id               uuid primary key,
    thread_id        uuid    not null references public.agent_thread(id),
    status           text    not null check (status in
                         ('queued', 'running', 'succeeded', 'failed', 'cancelled', 'dead')),
    model            text    not null,
    tokens_in        integer not null default 0,
    tokens_out       integer not null default 0,
    attempts         integer not null default 0,
    max_attempts     integer not null default 3,
    available_at     timestamptz not null default now(),  -- not claimable before this
    lease_owner      text,                                -- worker holding the run
    lease_until      timestamptz,                         -- when that claim goes stale
    cancel_requested boolean not null default false,
    error_code       text,
    created_at       timestamptz not null default now(),
    started_at       timestamptz,
    finished_at      timestamptz
);
create index if not exists agent_run_claimable
    on public.agent_run (status, available_at, created_at);

create table if not exists public.agent_run_step (
    id         bigint generated by default as identity primary key,
    run_id     uuid    not null references public.agent_run(id),
    seq        integer not null,
    kind       text    not null check (kind in ('model', 'tool')),
    tokens_in  integer not null default 0,
    tokens_out integer not null default 0,
    text       text,
    tool_calls jsonb,
    created_at timestamptz not null default now(),
    unique (run_id, seq)
);

create table if not exists public.agent_tool_call (
    id              bigint generated by default as identity primary key,
    run_step_id     bigint  not null unique references public.agent_run_step(id),
    tool_name       text    not null,
    args            jsonb   not null,
    result          jsonb   not null,
    ok              boolean not null,
    latency_ms      integer not null,
    idempotency_key text,
    created_at      timestamptz not null default now()
);


